package datatypes;

public class Escape {
    public static void main(String[]args){
        System.out.println("Hello my name is \"srishti!\"");
        System.out.println("Hello my name is \'srishti!\'");
        System.out.println("Hello my name is \\srishti!\\");
        System.out.println("Hello my name is srishti!\n");
        System.out.println("Hello my name is srishti!\b");
        System.out.println("Hello my name is srishti!\t");

    }
}
